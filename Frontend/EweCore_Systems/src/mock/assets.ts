// Get total quantity of all assets
export const getTotalAssetQuantity = (): number => {
  return mockAssets.reduce((sum, a) => sum + a.quantity, 0);
};

// Get assets by category
export const getAssetsByCategory = (category: string): Asset[] => {
  return mockAssets.filter(a => a.category === category);
};

// Get assets by department
export const getAssetsByDepartment = (department: string): Asset[] => {
  return mockAssets.filter(a => a.assignedDepartment === department);
};

// Get assets by employee
export const getAssetsByEmployee = (employeeId: string): Asset[] => {
  return mockAssets.filter(a => a.assignedToId === employeeId);
};

// Get assets needing maintenance soon (within 30 days)
export const getAssetsNeedingMaintenance = (): Asset[] => {
  const today = new Date();
  const thirtyDaysFromNow = new Date(today.getTime() + 30 * 24 * 60 * 60 * 1000);

  return mockAssets.filter(a => {
    if (!a.nextMaintenanceDate) return false;
    const maintenanceDate = new Date(a.nextMaintenanceDate);
    return maintenanceDate <= thirtyDaysFromNow && maintenanceDate >= today;
  });
};

// Get assets with expiring warranty (within 30 days)
export const getAssetsWithExpiringWarranty = (): Asset[] => {
  const today = new Date();
  const thirtyDaysFromNow = new Date(today.getTime() + 30 * 24 * 60 * 60 * 1000);

  return mockAssets.filter(a => {
    const warrantyEndDate = new Date(a.warrantyEndDate);
    return warrantyEndDate <= thirtyDaysFromNow && warrantyEndDate >= today;
  });
};

